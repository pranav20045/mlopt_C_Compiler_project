#include "mloptc/llvm_emitter.hpp"

#include <sstream>
#include <unordered_map>
#include <vector>

namespace mloptc {

namespace {

using namespace ir;

class LlvmEmitter {
public:
  explicit LlvmEmitter(const Module& module) : module_(module) {}

  std::string emit() {
    emitPrelude();
    emitGlobals();

    for (const Function& fn : module_.functions) {
      emitFunction(fn);
    }

    emitEntryPoint();
    return os_.str();
  }

private:
  void emitPrelude() {
    os_ << "; Generated by MLOpt-C. Link with runtime/mloptc_runtime.c:\n"
           ";   clang -O2 out.ll runtime/mloptc_runtime.c -o out\n"
           ";\n"
           "; NOTE: arithmetic is emitted WITHOUT nsw/nuw. ToyC arithmetic wraps\n"
           "; (docs/spec.md 7.1), and 'nsw' would tell LLVM to assume signed overflow\n"
           "; cannot happen -- licensing optimizations that disagree with the oracle on\n"
           "; exactly the programs that overflow.\n\n";

    os_ << "declare void @mloptc_print(i32)\n"
           "declare i32 @mloptc_div(i32, i32)\n"
           "declare i32 @mloptc_rem(i32, i32)\n"
           "declare i32 @mloptc_array_new(i32)\n"
           "declare ptr @mloptc_array_addr(i32, i32)\n"
           "declare i32 @mloptc_enter()\n"
           "declare void @mloptc_leave(i32)\n\n";
  }

  void emitGlobals() {
    for (const GlobalVarDecl& g : module_.globals) {
      // An array global holds a HANDLE, which can only be produced at runtime,
      // so it starts at 0 and is filled in by @__toyc_init_globals.
      os_ << "@g" << g.index << " = internal global i32 " << (g.isArray ? 0 : g.initValue)
          << '\n';
    }
    if (!module_.globals.empty()) {
      os_ << '\n';
    }

    os_ << "define internal void @__toyc_init_globals() {\nentry:\n";
    for (const GlobalVarDecl& g : module_.globals) {
      if (g.isArray) {
        os_ << "  %h" << g.index << " = call i32 @mloptc_array_new(i32 " << g.arraySize << ")\n";
        os_ << "  store i32 %h" << g.index << ", ptr @g" << g.index << '\n';
      }
    }
    os_ << "  ret void\n}\n\n";
  }

  /// `main` calls the ToyC `main`. Globals are initialised first, and the array
  /// handles they hold are allocated OUTSIDE any frame mark, so no
  /// mloptc_leave can free them.
  void emitEntryPoint() {
    os_ << "define i32 @main() {\nentry:\n"
           "  call void @__toyc_init_globals()\n"
           "  %r = call i32 @"
        << mangled(module_.functions[module_.mainIndex].name)
        << "()\n"
           "  ret i32 %r\n}\n";
  }

  static std::string mangled(const std::string& name) { return "toy_" + name; }

  /// An operand, as LLVM text.
  ///
  /// Constants are inlined rather than materialised into a register, and `move`
  /// is resolved here too -- both become pure bookkeeping instead of emitted
  /// instructions. That keeps the output readable and avoids leaning on clang
  /// to clean up noise we could simply not produce.
  std::string operand(ValueId id) const {
    if (id == kNoValue) {
      return "0";
    }
    const auto it = aliases_.find(id);
    if (it != aliases_.end()) {
      return it->second;
    }
    return "%v" + std::to_string(id);
  }

  std::string freshTemp() { return "%t" + std::to_string(tempCounter_++); }

  void emitFunction(const Function& fn) {
    aliases_.clear();
    tempCounter_ = 0;

    const bool returnsValue = fn.returnType == Type::Int;

    os_ << "define " << (returnsValue ? "i32" : "void") << " @" << mangled(fn.name) << '(';
    for (std::uint32_t i = 0; i < fn.numParams; ++i) {
      if (i > 0) {
        os_ << ", ";
      }
      os_ << "i32 %arg" << i;
    }
    os_ << ") {\n";

    // --- entry: frame slots ---
    os_ << "entry:\n";
    os_ << "  %framemark = call i32 @mloptc_enter()\n";

    for (std::uint32_t slot = 0; slot < fn.frameSize; ++slot) {
      os_ << "  %slot" << slot << " = alloca i32\n";
    }
    // Spec 7.4: every slot starts at zero. The IR also stores 0 explicitly for
    // declared locals, but zeroing here as well guarantees agreement with the
    // VM even for slots a particular path never initialises.
    for (std::uint32_t slot = 0; slot < fn.frameSize; ++slot) {
      os_ << "  store i32 0, ptr %slot" << slot << '\n';
    }
    for (std::uint32_t i = 0; i < fn.numParams; ++i) {
      os_ << "  store i32 %arg" << i << ", ptr %slot" << i << '\n';
    }
    os_ << "  br label %b" << fn.entry << "\n\n";

    for (const BasicBlock& block : fn.blocks) {
      os_ << "b" << block.id << ":\n";
      for (const Instruction& inst : block.instructions) {
        emitInstruction(inst, returnsValue);
      }
      os_ << '\n';
    }

    os_ << "}\n\n";
  }

  void emitInstruction(const Instruction& inst, bool returnsValue) {
    const std::string dest = "%v" + std::to_string(inst.dest);

    switch (inst.op) {
    case Opcode::Const:
      // No instruction: the literal is substituted wherever it is used.
      aliases_[inst.dest] = std::to_string(inst.imm);
      return;

    case Opcode::Move:
      aliases_[inst.dest] = operand(inst.a);
      return;

    case Opcode::Add:
      emitArith(dest, "add", inst);
      return;
    case Opcode::Sub:
      emitArith(dest, "sub", inst);
      return;
    case Opcode::Mul:
      emitArith(dest, "mul", inst);
      return;

    case Opcode::Div:
      os_ << "  " << dest << " = call i32 @mloptc_div(i32 " << operand(inst.a) << ", i32 "
          << operand(inst.b) << ")\n";
      return;
    case Opcode::Rem:
      os_ << "  " << dest << " = call i32 @mloptc_rem(i32 " << operand(inst.a) << ", i32 "
          << operand(inst.b) << ")\n";
      return;

    case Opcode::Lt:
      emitCompare(dest, "slt", inst);
      return;
    case Opcode::Le:
      emitCompare(dest, "sle", inst);
      return;
    case Opcode::Gt:
      emitCompare(dest, "sgt", inst);
      return;
    case Opcode::Ge:
      emitCompare(dest, "sge", inst);
      return;
    case Opcode::Eq:
      emitCompare(dest, "eq", inst);
      return;
    case Opcode::Ne:
      emitCompare(dest, "ne", inst);
      return;

    case Opcode::Neg:
      // No nsw: negating INT_MIN wraps to itself, and that is the defined
      // result (spec 7.1).
      os_ << "  " << dest << " = sub i32 0, " << operand(inst.a) << '\n';
      return;

    case Opcode::Not: {
      const std::string tmp = freshTemp();
      os_ << "  " << tmp << " = icmp eq i32 " << operand(inst.a) << ", 0\n";
      os_ << "  " << dest << " = zext i1 " << tmp << " to i32\n";
      return;
    }

    case Opcode::LoadLocal:
      os_ << "  " << dest << " = load i32, ptr %slot" << inst.imm << '\n';
      return;
    case Opcode::StoreLocal:
      os_ << "  store i32 " << operand(inst.a) << ", ptr %slot" << inst.imm << '\n';
      return;
    case Opcode::LoadGlobal:
      os_ << "  " << dest << " = load i32, ptr @g" << inst.imm << '\n';
      return;
    case Opcode::StoreGlobal:
      os_ << "  store i32 " << operand(inst.a) << ", ptr @g" << inst.imm << '\n';
      return;

    case Opcode::Alloca:
      os_ << "  " << dest << " = call i32 @mloptc_array_new(i32 " << inst.imm << ")\n";
      return;

    case Opcode::ArrayLoad: {
      const std::string addr = freshTemp();
      os_ << "  " << addr << " = call ptr @mloptc_array_addr(i32 " << operand(inst.a)
          << ", i32 " << operand(inst.b) << ")\n";
      os_ << "  " << dest << " = load i32, ptr " << addr << '\n';
      return;
    }

    case Opcode::ArrayStore: {
      const std::string addr = freshTemp();
      os_ << "  " << addr << " = call ptr @mloptc_array_addr(i32 " << operand(inst.a)
          << ", i32 " << operand(inst.b) << ")\n";
      os_ << "  store i32 " << operand(inst.c) << ", ptr " << addr << '\n';
      return;
    }

    case Opcode::Call: {
      const Function& callee = module_.functions[inst.funcIndex];
      const bool calleeReturns = callee.returnType == Type::Int;

      os_ << "  ";
      if (calleeReturns && inst.dest != kNoValue) {
        os_ << dest << " = ";
      }
      os_ << "call " << (calleeReturns ? "i32" : "void") << " @" << mangled(callee.name) << '(';
      for (std::size_t i = 0; i < inst.args.size(); ++i) {
        if (i > 0) {
          os_ << ", ";
        }
        os_ << "i32 " << operand(inst.args[i]);
      }
      os_ << ")\n";

      // A call whose result the IR discards still happens; if the callee
      // returns a value we simply do not name it.
      if (calleeReturns && inst.dest == kNoValue) {
        // Nothing further: LLVM allows discarding a call's result.
      }
      return;
    }

    case Opcode::Print:
      os_ << "  call void @mloptc_print(i32 " << operand(inst.a) << ")\n";
      return;

    case Opcode::Jump:
      os_ << "  br label %b" << inst.targetTrue << '\n';
      return;

    case Opcode::Branch: {
      const std::string tmp = freshTemp();
      os_ << "  " << tmp << " = icmp ne i32 " << operand(inst.a) << ", 0\n";
      os_ << "  br i1 " << tmp << ", label %b" << inst.targetTrue << ", label %b"
          << inst.targetFalse << '\n';
      return;
    }

    case Opcode::Return:
      // Releasing the frame mark before returning is what frees the arrays
      // this call allocated, matching the interpreter and the VM.
      os_ << "  call void @mloptc_leave(i32 %framemark)\n";
      if (returnsValue) {
        os_ << "  ret i32 " << (inst.a == kNoValue ? "0" : operand(inst.a)) << '\n';
      } else {
        os_ << "  ret void\n";
      }
      return;
    }
  }

  /// Emits a wrapping arithmetic instruction. The absence of `nsw` here is the
  /// single most important detail in this file.
  void emitArith(const std::string& dest, const char* op, const Instruction& inst) {
    os_ << "  " << dest << " = " << op << " i32 " << operand(inst.a) << ", " << operand(inst.b)
        << '\n';
  }

  void emitCompare(const std::string& dest, const char* pred, const Instruction& inst) {
    const std::string tmp = freshTemp();
    os_ << "  " << tmp << " = icmp " << pred << " i32 " << operand(inst.a) << ", "
        << operand(inst.b) << '\n';
    os_ << "  " << dest << " = zext i1 " << tmp << " to i32\n";
  }

  const Module& module_;
  std::ostringstream os_;

  /// ValueIds that are not materialised as registers: constants (inlined as
  /// literals) and moves (resolved to their source).
  std::unordered_map<ValueId, std::string> aliases_;
  std::uint32_t tempCounter_ = 0;
};

} // namespace

std::string emitLlvmIr(const ir::Module& module) {
  LlvmEmitter emitter(module);
  return emitter.emit();
}

} // namespace mloptc
